#!/usr/bin/env node
// Reuse proof (Req 1.3, 1.4): runs dependency-cruiser, writes docs/reuse-proof.md,
// and exits 1 when either app cannot reach any of the ten required packages.
import { spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const APPS = ['order-awaaz', 'bill-awaaz'];
const REQUIRED = [
  ['voice-capture', 'voice capture'],
  ['speech-provider', 'speech provider'],
  ['language-normalizer', 'normalization'],
  ['intent-engine', 'intent extraction'],
  ['catalog-matcher', 'catalog matching'],
  ['confidence-engine', 'confidence'],
  ['confirmation-engine', 'confirmation'],
  ['local-data', 'local data'],
  ['sync-engine', 'sync'],
  ['shared-ui', 'shared UI'],
];
const EXTRA = ['domain-order', 'domain-billing'];

const run = spawnSync(
  process.execPath,
  [
    resolve(root, 'node_modules/dependency-cruiser/bin/dependency-cruiser.mjs'),
    'apps',
    'packages',
    '--config',
    '.dependency-cruiser.cjs',
    '--output-type',
    'json',
  ],
  { cwd: root, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 },
);
let cruise;
try {
  cruise = JSON.parse(run.stdout);
} catch {
  console.error('reuse-report: could not parse dependency-cruiser output');
  console.error(run.stderr || run.stdout);
  process.exit(1);
}

/** Graph node = "app:<name>" or "pkg:<name>"; edges from non-test source files. */
const edges = new Map();
const files = new Map(); // `${app}|${pkg}` -> Set of direct importing files
const pkgOf = (dep) => {
  const m =
    /^@awaaz-kit\/([a-z-]+)/.exec(dep.module ?? '') ||
    /^(?:\.\.\/)*packages\/([a-z-]+)\//.exec((dep.resolved ?? '').replace(/\\/g, '/'));
  return m ? m[1] : null;
};
for (const mod of cruise.modules ?? []) {
  const source = mod.source.replace(/\\/g, '/');
  if (/\.(test|spec)\.[cm]?[jt]sx?$/.test(source)) continue;
  const m = /^(apps|packages)\/([^/]+)\//.exec(source);
  if (!m) continue;
  const node = `${m[1] === 'apps' ? 'app' : 'pkg'}:${m[2]}`;
  for (const dep of mod.dependencies ?? []) {
    const pkg = pkgOf(dep);
    if (!pkg || node === `pkg:${pkg}`) continue;
    if (!edges.has(node)) edges.set(node, new Set());
    edges.get(node).add(`pkg:${pkg}`);
    if (m[1] === 'apps') {
      const k = `${m[2]}|${pkg}`;
      if (!files.has(k)) files.set(k, new Set());
      files.get(k).add(source);
    }
  }
}

/** Route from app to pkg: 'direct', 'via domain-x' (shortest path), or null. */
const route = (app, pkg) => {
  const start = `app:${app}`;
  const target = `pkg:${pkg}`;
  if (edges.get(start)?.has(target)) return 'direct';
  const prev = new Map([[start, null]]);
  const queue = [start];
  while (queue.length) {
    const cur = queue.shift();
    for (const next of edges.get(cur) ?? []) {
      if (prev.has(next)) continue;
      prev.set(next, cur);
      if (next === target) {
        const path = [];
        for (let n = next; n !== start; n = prev.get(n)) path.unshift(n.slice(4));
        return `via ${path.slice(0, -1).join(' ? ')}`;
      }
      queue.push(next);
    }
  }
  return null;
};

const missing = [];
for (const [pkg] of REQUIRED) {
  for (const app of APPS) if (!route(app, pkg)) missing.push(`${app} -> ${pkg}`);
}

const cell = (app, pkg) => {
  const r = route(app, pkg);
  if (!r) return 'NOT REACHABLE';
  const n = files.get(`${app}|${pkg}`)?.size ?? 0;
  return r === 'direct' ? `direct (${n} files)` : r;
};
const row = (pkg, label) =>
  `| \`${pkg}\` | ${label} | ${cell(APPS[0], pkg)} | ${cell(APPS[1], pkg)} |`;
const lines = [
  '# Reuse proof',
  '',
  'Generated by `scripts/reuse-report.mjs` from dependency-cruiser output. Do not edit by hand.',
  '',
  'Each cell shows how the app reaches the package in the import graph (test files excluded):',
  '`direct` means an app file imports it; `via domain-xxx` means it is reached transitively',
  'through that package. The shortest route is shown.',
  '',
  '| Package | Capability | order-awaaz | bill-awaaz |',
  '| --- | --- | --- | --- |',
  ...REQUIRED.map(([p, l]) => row(p, l)),
  '',
  '## Domain packages (app specific by design)',
  '',
  '| Package | order-awaaz | bill-awaaz |',
  '| --- | --- | --- |',
  ...EXTRA.map((p) => `| \`${p}\` | ${cell(APPS[0], p)} | ${cell(APPS[1], p)} |`),
  '',
  `Result: ${missing.length === 0 ? 'PASS, both apps reach all ten required packages.' : 'FAIL'}`,
  ...(missing.length ? ['', 'Unreachable:', ...missing.map((m) => `- ${m}`)] : []),
  '',
];
mkdirSync(resolve(root, 'docs'), { recursive: true });
writeFileSync(resolve(root, 'docs/reuse-proof.md'), lines.join('\n'));

const shared = REQUIRED.filter(([p]) => APPS.every((a) => route(a, p))).length;
console.log(`reuse-report: ${shared}/${REQUIRED.length} required packages reached by both apps`);
console.log('reuse-report: wrote docs/reuse-proof.md');
if (missing.length) {
  console.error('reuse-report: FAIL, unreachable packages:');
  for (const m of missing) console.error(`  - ${m}`);
  process.exit(1);
}
